const HTML_ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
  '`': '&#96;',
};

/**
 * Hint بالعربي: دالة تحويل أي قيمة إلى نص آمن للعرض داخل HTML (نصاً أو داخل سمة attribute).
 *               المدخلات: أي قيمة. المخرجات: نص لا يمكن أن يُفسَّر كوسوم أو سكربت.
 */
export function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"'`]/g, (ch) => HTML_ESCAPES[ch]);
}
